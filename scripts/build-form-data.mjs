// Packs the official PDFs in forms/ into forms/form-data.js so the app can
// fill them without a web server (it works when the HTML file is opened
// directly). Run from the repo root after replacing a PDF:
//
//   node scripts/build-form-data.mjs
//
// No dependencies. Keys must match the `file` values in form-builder-mvp.html.

import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const FILES = {
  answerPacket: "forms/answer-packet-CCA-GF-1225-6003-CCA-GF-0626-6008.pdf",
  feeWaiverPacket: "forms/fee-waiver-packet-CCA-GF-0420-3012-3006-3007.pdf",
};

const lines = [
  "// Generated by scripts/build-form-data.mjs. Do not edit by hand.",
  "// Base64 copies of the official PDFs in forms/ (see forms/README.md).",
  "window.OFFICIAL_PDFS = {",
];
for (const [key, path] of Object.entries(FILES)) {
  const bytes = readFileSync(path);
  const sha = createHash("sha256").update(bytes).digest("hex");
  lines.push(`  // ${path} (sha256 ${sha})`);
  lines.push(`  ${key}: "${bytes.toString("base64")}",`);
  console.log(`${key}: ${path} (${bytes.length} bytes, sha256 ${sha.slice(0, 12)}...)`);
}
lines.push("};", "");
writeFileSync("forms/form-data.js", lines.join("\n"));
console.log("Wrote forms/form-data.js");
