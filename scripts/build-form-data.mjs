// Packs each official PDF in forms/ into its own script, forms/data/<key>.js,
// so the app can fill it without a web server (it works when the HTML file is
// opened directly) and only downloads the packet the person needs.
// Run from the repo root after replacing a PDF:
//
//   node scripts/build-form-data.mjs
//
// No dependencies. Keys must match the `file` values in app/official-forms.js.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const FILES = {
  answerPacket: "forms/answer-packet-CCA-GF-1225-6003-CCA-GF-0626-6008.pdf",
  feeWaiverPacket: "forms/fee-waiver-packet-CCA-GF-0420-3012-3006-3007.pdf",
  continuancePacket: "forms/continuance-packet-CCA-GF-1219-3000-3002.pdf",
};

mkdirSync("forms/data", { recursive: true });
for (const [key, path] of Object.entries(FILES)) {
  const bytes = readFileSync(path);
  const sha = createHash("sha256").update(bytes).digest("hex");
  const out = `forms/data/${key}.js`;
  writeFileSync(out, [
    "// Generated by scripts/build-form-data.mjs. Do not edit by hand.",
    `// Base64 copy of ${path} (sha256 ${sha}). See forms/README.md.`,
    "window.OFFICIAL_PDFS = window.OFFICIAL_PDFS || {};",
    `window.OFFICIAL_PDFS.${key} = "${bytes.toString("base64")}";`,
    "",
  ].join("\n"));
  console.log(`${out}: ${path} (${bytes.length} bytes, sha256 ${sha.slice(0, 12)}...)`);
}
